CREATE SCHEMA IF NOT EXISTS olivisit;
CREATE TABLE IF NOT EXISTS olivisit.admin (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL, 
    last_name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(10) NOT NULL UNIQUE,
    email VARCHAR(200) NOT NULL UNIQUE,
    password VARCHAR(255),
    created TIMESTAMP NOT NULL,
    modified TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS olivisit.roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    created TIMESTAMP NOT NULL,
    modified TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS olivisit.organisations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    code VARCHAR(154) NOT NULL UNIQUE,
    organisation_details TEXT,
    is_disabled BOOLEAN NOT NULL DEFAULT FALSE,
    created TIMESTAMP NOT NULL,
    modified TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS olivisit.houserules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    rule_description TEXT NOT NULL,
    organisation_id INTEGER NOT NULL,
    expiry_date TIMESTAMP,
    created TIMESTAMP NOT NULL,
    modified TIMESTAMP NOT NULL
);

-- Foreign Keys --
ALTER TABLE olivisit.houserules DROP CONSTRAINT IF EXISTS FK_ORGANISATIONS;
ALTER TABLE olivisit.houserules ADD CONSTRAINT FK_ORGANISATIONS FOREIGN KEY (organisation_id) REFERENCES olivisit.organisations(id);

CREATE TABLE IF NOT EXISTS olivisit.staff (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisation_id INTEGER NOT NULL,
    role_id INTEGER NOT NULL,
    first_name VARCHAR(50) NOT NULL, 
    last_name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(10) NOT NULL UNIQUE,
    email VARCHAR(200) NOT NULL UNIQUE,
    password VARCHAR(255),
    created TIMESTAMP NOT NULL,
    modified TIMESTAMP NOT NULL
);
 
-- Foreign Keys --
ALTER TABLE olivisit.staff DROP CONSTRAINT IF EXISTS FK_ORGANISATIONS;
ALTER TABLE olivisit.staff ADD CONSTRAINT FK_ORGANISATIONS FOREIGN KEY (organisation_id) REFERENCES olivisit.organisations(id);
ALTER TABLE olivisit.staff DROP CONSTRAINT IF EXISTS FK_ROLES;
ALTER TABLE olivisit.staff ADD CONSTRAINT FK_ROLES FOREIGN KEY (role_id) REFERENCES olivisit.roles(id);

CREATE TABLE IF NOT EXISTS olivisit.visitors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisation_id INTEGER NOT NULL,
    first_name VARCHAR(50) NOT NULL, 
    last_name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(10) NOT NULL,
    email VARCHAR(200) NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP,
    created TIMESTAMP NOT NULL,
    modified TIMESTAMP NOT NULL
);
 
-- Foreign Keys --
ALTER TABLE olivisit.visitors DROP CONSTRAINT IF EXISTS FK_ORGANISATIONS;
ALTER TABLE olivisit.visitors ADD CONSTRAINT FK_ORGANISATIONS FOREIGN KEY (organisation_id) REFERENCES olivisit.organisations(id);

