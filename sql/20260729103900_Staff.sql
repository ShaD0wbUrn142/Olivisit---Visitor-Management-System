CREATE TABLE IF NOT EXISTS olivisit.staff (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organisation_id INTEGER NOT NULL,
    role_id INTEGER NOT NULL,
    first_name VARCHAR(50) NOT NULL, 
    last_name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(10) NOT NULL UNIQUE,
    email VARCHAR(200) NOT NULL UNIQUE,
    password VARCHAR(255),
    created TIMESTAMP NOT NULL,
    modified TIMESTAMP NOT NULL
);
 
-- Foreign Keys --
ALTER TABLE olivisit.staff DROP CONSTRAINT IF EXISTS FK_ORGANISATIONS;
ALTER TABLE olivisit.staff ADD CONSTRAINT FK_ORGANISATIONS FOREIGN KEY (organisation_id) REFERENCES olivisit.organisations(id);
ALTER TABLE olivisit.staff DROP CONSTRAINT IF EXISTS FK_ROLES;
ALTER TABLE olivisit.staff ADD CONSTRAINT FK_ROLES FOREIGN KEY (role_id) REFERENCES olivisit.roles(id);

